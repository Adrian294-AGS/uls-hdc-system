<?php

namespace App\Support\Exports;

use App\Models\CumulativeRecord;
use App\Models\EntranceTestResult;
use App\Models\IntakeInterview;
use App\Models\User;
use App\Support\Form5;
use App\Support\Form8;
use Carbon\CarbonImmutable;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\Storage;

/**
 * One student's record as a format-neutral document (header, photo, sections of label/value
 * fields and tables), rendered to PDF, Excel or Word. It follows the paper HDC Form 5 order.
 * Callers decide what may be included (SATA, Form 8); this class never checks permissions.
 */
final class RecordDocument
{
    public const UNIVERSITY = 'University of La Salette';

    public const CENTER = 'The Human Development Center';

    public const CITY = 'Santiago City';

    public const CONFIDENTIAL = 'CONFIDENTIAL';

    /**
     * @param  array<string, string>  $meta
     * @param  array{data: string, mime: string, extension: string}|null  $photo
     * @param  list<array{title: string, fields: list<array{0: string, 1: string}>, tables: list<array{title: string, headers: list<string>, rows: list<list<string>>}>, pageBreak: bool}>  $sections
     */
    public function __construct(
        public readonly string $title,
        public readonly string $studentName,
        public readonly string $studentNumber,
        public readonly array $meta,
        public readonly ?array $photo,
        public readonly array $sections,
        public readonly string $generatedLine,
    ) {}

    /**
     * @param  Collection<int, EntranceTestResult>|null  $sata  SATA results to include (null = leave out)
     * @param  Collection<int, IntakeInterview>|null  $intakes  intake interviews to include (null = leave out)
     */
    public static function build(CumulativeRecord $record, User $generatedBy, ?Collection $sata = null, ?Collection $intakes = null): self
    {
        $record->loadMissing(['student.program.college', 'program.college', 'parents', 'siblings', 'schools', 'organizations']);
        $student = $record->student;

        $sections = self::form5Sections($record);

        if ($sata !== null) {
            $sections[] = self::sataSection($sata);
        }

        foreach ($intakes ?? [] as $index => $interview) {
            array_push($sections, ...self::intakeSections($interview, $index === 0));
        }

        return new self(
            title: 'HDC Form 5 · Student Cumulative Record',
            studentName: $record->fullName() ?: $student->name,
            studentNumber: (string) $student->student_number,
            meta: [
                'Student no.' => (string) $student->student_number,
                'Program / College' => trim(($student->program?->code ?? '').' – '.($student->program?->college?->name ?? ''), ' –'),
                'Term' => trim((Form5::SEMESTERS[$record->semester] ?? '').', S.Y. '.$record->school_year, ', '),
                'Status' => $record->status->label().($record->submitted_at ? ' (submitted '.self::localDate($record->submitted_at, 'F j, Y').')' : ''),
            ],
            photo: self::photo($record),
            sections: $sections,
            generatedLine: 'Generated by '.$generatedBy->name.' ('.$generatedBy->role->label().') on '.self::localDate(now(), 'F j, Y g:i A'),
        );
    }

    /**
     * File name such as HDC_Form5_24-10350_2026-10-20.pdf
     */
    public function filename(string $extension): string
    {
        $number = preg_replace('/[^A-Za-z0-9-]/', '', $this->studentNumber) ?: 'student';

        return 'HDC_Form5_'.$number.'_'.self::localDate(now(), 'Y-m-d').'.'.$extension;
    }

    /**
     * @return list<array{title: string, fields: list<array{0: string, 1: string}>, tables: list<array{title: string, headers: list<string>, rows: list<list<string>>}>, pageBreak: bool}>
     */
    private static function form5Sections(CumulativeRecord $record): array
    {
        $yesNo = fn (?bool $value) => $value === null ? '' : ($value ? 'Yes' : 'No');
        $option = fn (array $options, $key) => $key === null ? '' : (string) ($options[$key] ?? $key);
        $list = fn (array $options, ?array $keys) => implode(', ', Form5::labels($options, $keys));

        $parents = [];
        foreach (Form5::PARENT_RELATIONS as $relation => $label) {
            $parent = $record->parent($relation);
            $parents[] = [$label, $parent?->name, $parent?->age, $parent?->religion, $parent?->occupation, $parent?->monthly_income, $parent?->educational_attainment];
        }

        return [
            self::section(Form5::STEPS['entry'], [
                'Month of entry' => $option(Form5::MONTHS, $record->month_of_entry),
                'School year' => $record->school_year,
                'Semester' => $option(Form5::SEMESTERS, $record->semester),
                'Student type' => $option(Form5::STUDENT_TYPES, $record->student_type),
            ]),
            self::section(Form5::STEPS['personal'], [
                'Name' => $record->fullName(),
                'Course preference' => $record->program ? $record->program->code.' – '.$record->program->name : '',
                'Year level' => $option(Form5::YEAR_LEVELS, $record->year_level),
                'Major' => $record->major,
                'Home address' => $record->home_address,
                'Birth date' => $record->birth_date?->format('F j, Y'),
                'Age' => $record->age(),
                'Place of birth' => $record->place_of_birth,
                'Sex' => $option(Form5::SEXES, $record->sex),
                'Civil status' => $option(Form5::CIVIL_STATUSES, $record->civil_status),
                'Spouse name' => $record->spouse_name,
                'No. of children' => $record->number_of_children,
                'Mobile no.' => $record->contact_number,
                'E-mail address' => $record->email,
                'Nationality' => $record->nationality,
                'Religion' => $record->religion,
                'Ethnicity' => $record->ethnicity,
                'Boarding house address' => $record->boarding_address,
                'Emergency contact name' => $record->emergency_contact_name,
                'Emergency contact address' => $record->emergency_contact_address,
                'Emergency contact no.' => $record->emergency_contact_number,
            ]),
            self::section(Form5::STEPS['family'], [
                "Parents' status" => $list(Form5::PARENTS_STATUSES, $record->parents_status),
                'How do you see your family at present?' => $record->family_view,
                'Specific concern regarding your family' => $record->family_concern,
                'Dialect/language spoken at home' => $record->home_language,
            ], [
                self::table('Parents', ['', 'Name', 'Age', 'Religion', 'Occupation', 'Monthly income', 'Educational attainment'], $parents),
                self::table('Siblings (including the student)', ['Name', 'Sex', 'Age', 'Yr./Course/School', 'Occupation/Office'],
                    $record->siblings->map(fn ($s) => [$s->name, $option(Form5::SEXES, $s->sex), $s->age, $s->year_course_school, $s->occupation])->all()),
            ]),
            self::section(Form5::STEPS['health'], [
                'Height' => $record->height,
                'Weight' => $record->weight,
                'Handicap' => $record->handicap,
                'Normal eyesight' => $yesNo($record->normal_eyesight),
                'Normal hearing' => $yesNo($record->normal_hearing),
                'Persistent illness' => $record->persistent_illness,
                'Hospitalized' => $yesNo($record->hospitalized),
                'Reason for hospitalization' => $record->hospitalization_reason,
                'Surgical operation' => $yesNo($record->had_surgery),
                'Surgery details' => $record->surgery_details,
                'Allergies' => $yesNo($record->has_allergies),
                'Allergy details' => $record->allergy_details,
            ]),
            self::section(Form5::STEPS['education'], [
                'Scholarships and honors received' => $record->scholarships_honors,
                'Nature of schooling' => $option(Form5::SCHOOLING_NATURES, $record->schooling_nature),
                'If interrupted, why?' => $record->interruption_reason,
                'Scholarship you wish to apply for' => $record->scholarship_to_apply,
                'Subject(s) with difficulty' => $record->difficult_subjects,
                'Best-liked subject(s)' => $record->best_liked_subjects,
                'Educational facilities at home' => $list(Form5::HOME_FACILITIES, $record->home_facilities),
                'Book recently finished' => $record->recent_book,
            ], [
                self::table('Schools attended', ['Level', 'School', 'Place', 'Inclusive years', 'General average'],
                    $record->schools->map(fn ($s) => [$option(Form5::SCHOOL_LEVELS, $s->level), $s->school_name, $s->place, $s->inclusive_years, $s->grade_average])->all()),
            ]),
            self::section(Form5::STEPS['vocational'], [
                'Reason in choosing the course' => $list(Form5::COURSE_REASONS, $record->course_reasons),
                'Other reason (specify)' => $record->course_reason_other,
                'Second course alternative' => $record->second_course,
                'Occupation/job seriously considered, and why' => $record->considered_occupation,
                'Work experience as a student' => $yesNo($record->has_work_experience),
                'When' => $record->work_experience_when,
                'Specific work experience' => $record->work_experience_details,
                'What the student likes about it' => $record->work_experience_likes,
            ]),
            self::section(Form5::STEPS['social'], [
                'Leisure-time activities/hobbies' => $record->hobbies,
            ], [
                self::table('Club/organization memberships', ['Organization', 'Activity/position'],
                    $record->organizations->map(fn ($o) => [$o->organization, $o->activity])->all()),
            ]),
            self::section(Form5::STEPS['self'], [
                'Self-description' => $list(Form5::SELF_DESCRIPTIONS, $record->self_description),
            ]),
            self::section(Form5::STEPS['skills'], [
                'Skills to develop' => $list(Form5::SKILLS, $record->skills_to_develop),
                'Other skills (specify)' => $record->skills_other,
                'Willing to talk with a counselor' => $yesNo($record->willing_to_see_counselor),
                'Why?' => $record->counselor_willingness_reason,
            ]),
            self::section('Data Privacy Consent', [
                'Consent given' => $record->consent_given ? 'Yes' : 'No',
                'Signature over printed name' => $record->consent_name,
                'Date' => $record->consented_at ? self::localDate($record->consented_at, 'F j, Y') : '',
            ]),
        ];
    }

    /**
     * @param  Collection<int, EntranceTestResult>  $results
     * @return array{title: string, fields: list<array{0: string, 1: string}>, tables: list<array{title: string, headers: list<string>, rows: list<list<string>>}>, pageBreak: bool}
     */
    private static function sataSection(Collection $results): array
    {
        $result = $results->first();

        if (! $result) {
            return self::section('Entrance Test Result (SATA)', ['Result' => 'No SATA result has been encoded.'], [], pageBreak: true);
        }

        $rows = [];
        foreach (EntranceTestResult::subtests() as $key => $subtest) {
            $rows[] = [$subtest['code'], $subtest['name'], $result->{$key.'_score'}, $result->{$key.'_descriptor'}];
        }

        return self::section('Entrance Test Result (SATA)', [
            'Date of examination' => $result->exam_date?->format('F j, Y'),
            'Quotient' => $result->quotient,
            'Quotient descriptor' => $result->quotient_descriptor,
            'Remarks' => $result->remarks,
            'Encoded by' => $result->encoder?->name,
            'Other results on file' => $results->count() > 1 ? ($results->count() - 1).' older result(s)' : 'None',
        ], [
            self::table('Scholastic Abilities Test for Adults', ['Code', 'Subtest', 'Standard score', 'Descriptor'], $rows),
        ], pageBreak: true);
    }

    /**
     * @return list<array{title: string, fields: list<array{0: string, 1: string}>, tables: list<array{title: string, headers: list<string>, rows: list<list<string>>}>, pageBreak: bool}>
     */
    private static function intakeSections(IntakeInterview $interview, bool $first): array
    {
        $answer = fn (?bool $value) => $value === null ? '' : ($value ? 'Yes' : 'No');
        $yesNoRows = fn (array $items) => collect($items)->map(fn (string $label, string $key) => [$label, $answer($interview->{$key})])->values()->all();
        $date = $interview->interview_at ? self::localDate($interview->interview_at, 'F j, Y g:i A', convert: false) : 'Not set';

        return [
            self::section('HDC Form 8 · Intake Interview ('.$date.')', [
                'Status' => $interview->status->label(),
                'Interviewer' => $interview->counselor?->name,
                'Interviewee acknowledged' => $interview->interviewee_acknowledged ? 'Yes' : 'No',
                'Date of entry' => $interview->date_of_entry?->format('F j, Y'),
                'Academic status' => $interview->academic_status,
            ], [], pageBreak: true),
            self::section('I. Personal Data (at the time of the interview)', [
                'Name' => $interview->name,
                'Nickname' => $interview->nickname,
                'Course' => $interview->course,
                'Complete home address' => $interview->home_address,
                'Age' => $interview->age,
                'Sex' => Form5::SEXES[$interview->sex] ?? '',
                'Birthdate' => $interview->birth_date?->format('F j, Y'),
                'Place of birth' => $interview->place_of_birth,
                'Civil status' => Form5::CIVIL_STATUSES[$interview->civil_status] ?? '',
                'If married, name of spouse' => $interview->spouse_name,
                'No. of children' => $interview->number_of_children,
                'Citizenship' => $interview->citizenship === 'other' ? (string) $interview->citizenship_other : (Form8::CITIZENSHIPS[$interview->citizenship] ?? ''),
                'Religion' => $interview->religion,
                'Contact no.' => $interview->contact_number,
                'Boarding house address' => $interview->boarding_address,
                'Emergency contact' => $interview->emergency_contact_name,
                'Relationship' => $interview->emergency_contact_relationship,
                'Emergency contact address' => $interview->emergency_contact_address,
                'Emergency contact no.' => $interview->emergency_contact_number,
            ]),
            self::section('II. Psychological Concerns', ['Specify' => $interview->concerns_specify], [
                self::table('', ['Concern', 'Answer'], $yesNoRows(Form8::CONCERNS)),
            ]),
            self::section('Relationship Concerns', ['Others (specify)' => $interview->relationship_other], [
                self::table('', ['Concern', 'Answer'], $yesNoRows(Form8::RELATIONSHIP_CONCERNS)),
            ]),
            self::section('III. Coping Strategies', ['Others (specify)' => $interview->coping_other], [
                self::table('', ['Strategy', 'Answer'], $yesNoRows(Form8::COPING_STRATEGIES)),
            ]),
            self::section('IV–VIII. Counselor Notes', [
                Form8::NOTES['client_description'] => $interview->client_description,
                Form8::NOTES['presenting_concerns'] => $interview->presenting_concerns,
                'VI. Relationship with the client during the intake summary' => implode(', ', Form5::labels(Form8::RELATIONSHIP_DURING_INTAKE, $interview->relationship_during_intake)),
                Form8::NOTES['conceptualization'] => $interview->conceptualization,
                Form8::NOTES['recommendations'] => $interview->recommendations,
            ]),
        ];
    }

    /**
     * @param  array<string, mixed>  $fields
     * @param  list<array{title: string, headers: list<string>, rows: list<list<string>>}>  $tables
     * @return array{title: string, fields: list<array{0: string, 1: string}>, tables: list<array{title: string, headers: list<string>, rows: list<list<string>>}>, pageBreak: bool}
     */
    private static function section(string $title, array $fields, array $tables = [], bool $pageBreak = false): array
    {
        $pairs = [];
        foreach ($fields as $label => $value) {
            $pairs[] = [(string) $label, (string) ($value ?? '')];
        }

        return ['title' => $title, 'fields' => $pairs, 'tables' => $tables, 'pageBreak' => $pageBreak];
    }

    /**
     * @param  list<string>  $headers
     * @param  array<int, array<int, mixed>>  $rows
     * @return array{title: string, headers: list<string>, rows: list<list<string>>}
     */
    private static function table(string $title, array $headers, array $rows): array
    {
        return [
            'title' => $title,
            'headers' => $headers,
            'rows' => array_map(fn (array $row) => array_map(fn ($cell) => (string) ($cell ?? ''), array_values($row)), $rows),
        ];
    }

    /**
     * @return array{data: string, mime: string, extension: string}|null
     */
    private static function photo(CumulativeRecord $record): ?array
    {
        if (! $record->photo_path || ! Storage::exists($record->photo_path)) {
            return null;
        }

        $mime = (string) Storage::mimeType($record->photo_path);
        $extension = match ($mime) {
            'image/png' => 'png',
            'image/webp' => 'webp',
            default => 'jpg',
        };

        return ['data' => (string) Storage::get($record->photo_path), 'mime' => $mime, 'extension' => $extension];
    }

    /**
     * Dates are stored in UTC; documents show Philippine time. Intake interview times are stored as
     * typed by the counselor, so they are shown as-is ($convert = false).
     */
    private static function localDate(\DateTimeInterface $date, string $format, bool $convert = true): string
    {
        $date = CarbonImmutable::instance($date);

        return ($convert ? $date->setTimezone(config('hdc.local_timezone', 'Asia/Manila')) : $date)->format($format);
    }
}
