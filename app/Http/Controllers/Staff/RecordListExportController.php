<?php

namespace App\Http\Controllers\Staff;

use App\Http\Controllers\Controller;
use App\Models\AccessLog;
use App\Models\College;
use App\Models\Program;
use App\Models\User;
use App\Support\Exports\DocumentWriter;
use App\Support\Form5;
use App\Support\StudentRecordQuery;
use Carbon\CarbonImmutable;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Validation\Rule;
use Symfony\Component\HttpFoundation\BinaryFileResponse;
use Throwable;

/**
 * The staff records list (with its current filters) as Excel, CSV or PDF. Same college scoping as
 * the list. Only the director may add sensitive Form 5/SATA columns; Form 8 answers are never
 * exported in a list. Logged as "export_list".
 */
class RecordListExportController extends Controller
{
    public const FORMATS = ['xlsx', 'csv', 'pdf'];

    /**
     * dompdf gets slow and memory-hungry beyond this; Excel/CSV have no limit.
     */
    public const MAX_PDF_ROWS = 1000;

    public function __invoke(Request $request): BinaryFileResponse|RedirectResponse
    {
        $validated = $request->validate([
            'format' => ['required', Rule::in(self::FORMATS)],
            'sensitive' => ['nullable', 'boolean'],
        ]);
        $format = $validated['format'];
        $sensitive = (bool) ($validated['sensitive'] ?? false);

        abort_if($sensitive && ! $request->user()->isDirector(), 403);

        $query = StudentRecordQuery::fromRequest($request);
        $students = $query->students()
            ->with(['program.college', 'latestCumulativeRecord', 'latestEntranceTestResult'])
            ->withExists('entranceTestResults as has_sata')
            ->withIntakeSummary()
            ->orderBy('users.last_name')
            ->orderBy('users.first_name')
            ->get();

        $listUrl = route('staff.records.index', array_filter($request->only(EntranceTestResultController::LIST_FILTERS), 'filled'));

        if ($format === 'pdf' && $students->count() > self::MAX_PDF_ROWS) {
            return redirect($listUrl)->with('error', __('This list has :count students. PDF is limited to :max rows; please use Excel or CSV, or narrow the filters.', [
                'count' => $students->count(), 'max' => self::MAX_PDF_ROWS,
            ]));
        }

        $headers = ['Last name', 'First name', 'Middle name', 'Student no.', 'Program', 'College', 'Year level', 'Form 5 status', 'Submitted', 'SATA encoded', 'Intake status'];
        if ($sensitive) {
            $headers = [...$headers, 'Sex', 'Birth date', 'Civil status', 'Mobile no.', 'E-mail', 'Home address', 'Religion', 'Emergency contact', 'Emergency contact no.', 'SATA quotient', 'SATA quotient descriptor'];
        }

        $rows = $students->map(function (User $student) use ($sensitive): array {
            $record = $student->latestCumulativeRecord;
            $row = [
                $student->last_name, $student->first_name, $student->middle_name, $student->student_number,
                $student->program?->code, $student->program?->college?->code, Form5::YEAR_LEVELS[$student->year_level] ?? '',
                $record?->status->label() ?? 'Not started',
                $record?->submitted_at ? CarbonImmutable::instance($record->submitted_at)->setTimezone(config('hdc.local_timezone'))->format('Y-m-d') : '',
                $student->has_sata ? 'Yes' : 'No',
                $student->latestIntakeInterview?->status->label() ?? 'None',
            ];

            if ($sensitive) {
                $sata = $student->latestEntranceTestResult;
                $row = [...$row,
                    Form5::SEXES[$record?->sex] ?? '', $record?->birth_date?->format('Y-m-d'), Form5::CIVIL_STATUSES[$record?->civil_status] ?? '',
                    $record?->contact_number, $record?->email, $record?->home_address, $record?->religion,
                    $record?->emergency_contact_name, $record?->emergency_contact_number, $sata?->quotient, $sata?->quotient_descriptor,
                ];
            }

            return array_map(fn ($cell) => (string) ($cell ?? ''), $row);
        })->all();

        $filters = $this->describeFilters($query);
        $title = 'Student Records'.($sensitive ? ' (with sensitive fields)' : '');
        $user = $request->user();
        $generatedLine = 'Generated by '.$user->name.' ('.$user->role->label().') on '.now(config('hdc.local_timezone'))->format('F j, Y g:i A');

        try {
            $path = DocumentWriter::listFile($format, $title, $headers, $rows, $filters, $generatedLine);
        } catch (Throwable $exception) {
            report($exception);

            return redirect($listUrl)->with('error', __('The list could not be exported. Please try again, or choose another format.'));
        }

        AccessLog::create([
            'user_id' => $user->id,
            'action' => AccessLog::ACTION_EXPORT_LIST,
            'details' => mb_substr("format: {$format}; students: ".count($rows).'; sensitive: '.($sensitive ? 'yes' : 'no').'; '.DocumentWriter::describeFilters($filters), 0, 500),
            'ip' => $request->ip(),
        ]);

        $filename = 'HDC_Student_Records_'.now(config('hdc.local_timezone'))->format('Y-m-d').'.'.$format;

        return response()
            ->download($path, $filename, ['Content-Type' => DocumentWriter::FORMATS[$format]['mime']])
            ->deleteFileAfterSend();
    }

    /**
     * @return array<string, string>
     */
    private function describeFilters(StudentRecordQuery $query): array
    {
        $filters = $query->filters();

        return array_filter([
            'Search' => $filters['q'] ?? null,
            'College' => ($filters['college_id'] ?? null) ? College::find($filters['college_id'])?->code : null,
            'Program' => ($filters['program_id'] ?? null) ? Program::find($filters['program_id'])?->code : null,
            'Year level' => Form5::YEAR_LEVELS[$filters['year_level'] ?? 0] ?? null,
            'Form 5 status' => StudentRecordQuery::STATUSES[$filters['status'] ?? ''] ?? null,
            'SATA' => StudentRecordQuery::SATA_FILTERS[$filters['sata'] ?? ''] ?? null,
            'Intake' => StudentRecordQuery::INTAKE_FILTERS[$filters['intake'] ?? ''] ?? null,
        ]);
    }
}
