<?php

namespace App\Http\Controllers\Staff;

use App\Http\Controllers\Controller;
use App\Models\AccessLog;
use App\Support\Form5;
use App\Support\Reports\Report;
use App\Support\Reports\ReportFilters;
use App\Support\Reports\ReportResult;
use App\Support\Reports\Suppression;
use Illuminate\Http\Request;
use Illuminate\Support\Str;
use Illuminate\View\View;
use Symfony\Component\HttpFoundation\StreamedResponse;

/**
 * Aggregate reports (FR-09). Every number is a suppressed count; no page links a count to
 * the students behind it. Each view is logged as "view_report", each CSV/print as "export_report".
 */
class ReportController extends Controller
{
    public function show(Request $request, string $report = 'concerns'): View
    {
        [$report, $filters, $result] = $this->run($request, $report);
        $this->log($request, AccessLog::ACTION_VIEW_REPORT, $report, $filters);

        return view('reports.show', [
            'report' => $report,
            'reports' => array_map(fn (string $class) => new $class, Report::REPORTS),
            'filters' => $filters,
            'result' => $result,
            'schoolYears' => ReportFilters::schoolYearOptions(),
            'semesters' => Form5::SEMESTERS,
            'yearLevels' => Form5::YEAR_LEVELS,
        ]);
    }

    public function print(Request $request, string $report): View
    {
        [$report, $filters, $result] = $this->run($request, $report);
        $this->log($request, AccessLog::ACTION_EXPORT_REPORT, $report, $filters, 'print');

        return view('reports.print', [
            'report' => $report,
            'filters' => $filters,
            'result' => $result,
            'generatedAt' => now(),
            'generatedBy' => $request->user(),
        ]);
    }

    public function csv(Request $request, string $report): StreamedResponse
    {
        [$report, $filters, $result] = $this->run($request, $report);
        $this->log($request, AccessLog::ACTION_EXPORT_REPORT, $report, $filters, 'csv');

        $user = $request->user();
        $filename = 'hdc-'.Str::slug($report->title()).'-'.now()->format('Y-m-d').'.csv';

        return response()->streamDownload(function () use ($report, $filters, $result, $user): void {
            $out = fopen('php://output', 'w');
            $write = fn (array $row) => fputcsv($out, array_map(self::csvCell(...), $row), escape: '');

            $write(['ULS Human Development Center: '.$report->title()]);
            $write(['Generated', now()->format('Y-m-d H:i')]);
            $write(['Generated by', $user->name.' ('.$user->role->label().')']);
            foreach ($filters->describe() as $label => $value) {
                $write([$label, $value]);
            }
            $write(['Note', 'Counts from 1 to '.(Suppression::minimum() - 1).' are shown as "'.Suppression::marker().'".']);
            $write([]);

            foreach ($result->summary as $item) {
                $write([$item['label'], $item['value']]);
            }

            foreach ($result->tables as $table) {
                $write([]);
                $write([$table->title]);
                $write($table->headers);
                foreach ($table->rows as $row) {
                    $write($row);
                }
                if ($table->note) {
                    $write([$table->note]);
                }
            }

            fclose($out);
        }, $filename, ['Content-Type' => 'text/csv; charset=UTF-8']);
    }

    /**
     * @return array{0: Report, 1: ReportFilters, 2: ReportResult}
     */
    private function run(Request $request, string $key): array
    {
        $report = Report::make($key);
        abort_unless($report, 404);

        $filters = ReportFilters::fromRequest($request);

        return [$report, $filters, $report->build($filters)];
    }

    private function log(Request $request, string $action, Report $report, ReportFilters $filters, ?string $format = null): void
    {
        $details = collect($filters->describe())->map(fn (string $value, string $label) => "{$label}: {$value}")->implode('; ');

        AccessLog::create([
            'user_id' => $request->user()->id,
            'action' => $action,
            'details' => Str::limit($report->key().($format ? " ({$format})" : '')." | {$details}", 497),
            'ip' => $request->ip(),
        ]);
    }

    /**
     * Stop spreadsheet apps from treating a cell (e.g. a college name) as a formula.
     */
    private static function csvCell(?string $value): string
    {
        $value = (string) $value;

        return $value !== '' && in_array($value[0], ['=', '+', '-', '@', "\t", "\r"], true) ? "'".$value : $value;
    }
}
