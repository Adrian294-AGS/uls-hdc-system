<?php

namespace Tests\Feature;

use App\Models\AccessLog;
use App\Models\College;
use App\Models\CumulativeRecord;
use App\Models\EntranceTestResult;
use App\Models\IntakeInterview;
use App\Models\Program;
use App\Models\User;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Testing\TestResponse;
use PhpOffice\PhpSpreadsheet\IOFactory;
use Symfony\Component\HttpFoundation\BinaryFileResponse;
use Tests\TestCase;
use ZipArchive;

/**
 * Phase 2: single student exports (PDF, Excel, Word) and list exports (Excel, CSV, PDF).
 */
class ExportTest extends TestCase
{
    use RefreshDatabase;

    private User $counselorA;

    private User $counselorB;

    private User $director;

    private User $studentA;

    private CumulativeRecord $recordA;

    protected function setUp(): void
    {
        parent::setUp();

        $collegeA = College::factory()->create(['code' => 'CIT']);
        $collegeB = College::factory()->create(['code' => 'CON']);
        $this->counselorA = User::factory()->counselor([$collegeA])->create();
        $this->counselorB = User::factory()->counselor([$collegeB])->create();
        $this->director = User::factory()->director()->create();
        $this->studentA = User::factory()->student(Program::factory()->for($collegeA)->create(['code' => 'BSIT']))
            ->create(['last_name' => 'Aquino', 'student_number' => '24-10001', 'year_level' => 1]);
        $this->recordA = CumulativeRecord::factory()->submitted()->for($this->studentA, 'student')
            ->create(['first_name' => 'Ana', 'last_name' => 'Aquino', 'contact_number' => '09170000001']);
        EntranceTestResult::factory()->for($this->studentA, 'student')->create(['quotient' => 111]);
        IntakeInterview::factory()->finalized()->for($this->studentA, 'student')->create(['presenting_concerns' => 'Secret intake note']);
    }

    /**
     * Read a downloaded file, then delete it (tests never "send" the response, which is what deletes it).
     */
    private function downloaded(TestResponse $response): string
    {
        $this->assertInstanceOf(BinaryFileResponse::class, $response->baseResponse);
        $path = $response->baseResponse->getFile()->getPathname();
        $contents = file_get_contents($path);
        unlink($path);

        return $contents;
    }

    /**
     * All cell values of the first sheet of an .xlsx download.
     *
     * @return list<string>
     */
    private function xlsxCells(TestResponse $response): array
    {
        $path = tempnam(sys_get_temp_dir(), 'xlsx').'.xlsx';
        file_put_contents($path, $this->downloaded($response));
        $rows = IOFactory::load($path)->getActiveSheet()->toArray();
        unlink($path);

        return array_values(array_filter(array_map('strval', array_merge(...$rows)), 'strlen'));
    }

    // ---- Single student ---------------------------------------------------------------------

    public function test_staff_can_export_a_record_as_pdf_excel_and_word_with_a_dated_filename(): void
    {
        $today = now(config('hdc.local_timezone'))->format('Y-m-d');

        $pdf = $this->actingAs($this->counselorA)->get(route('staff.records.export', [$this->recordA, 'format' => 'pdf']))->assertOk();
        $pdf->assertDownload("HDC_Form5_24-10001_{$today}.pdf");
        $this->assertStringStartsWith('%PDF', $this->downloaded($pdf));

        $xlsx = $this->actingAs($this->counselorA)->get(route('staff.records.export', [$this->recordA, 'format' => 'xlsx']))->assertDownload("HDC_Form5_24-10001_{$today}.xlsx");
        $cells = $this->xlsxCells($xlsx);
        foreach (['University of La Salette', 'The Human Development Center', 'Santiago City', 'CONFIDENTIAL', 'PERSONAL DATA', 'FAMILY BACKGROUND', 'DATA PRIVACY CONSENT', '09170000001'] as $expected) {
            $this->assertContains($expected, $cells);
        }
        $this->assertNotEmpty(preg_grep('/^Generated by .+\(Counselor\) on /', $cells));

        $docx = $this->actingAs($this->counselorA)->get(route('staff.records.export', [$this->recordA, 'format' => 'docx']))->assertDownload("HDC_Form5_24-10001_{$today}.docx");
        $path = tempnam(sys_get_temp_dir(), 'docx');
        file_put_contents($path, $this->downloaded($docx));
        $zip = new ZipArchive;
        $this->assertTrue($zip->open($path) === true);
        $this->assertStringContainsString('Ana Aquino', $zip->getFromName('word/document.xml'));
        $this->assertStringContainsString('CONFIDENTIAL', implode('', array_map(fn ($i) => (string) $zip->getFromIndex($i), range(0, $zip->numFiles - 1))));
        $zip->close();
        unlink($path);
    }

    public function test_sata_and_form_8_are_included_only_when_asked(): void
    {
        $without = $this->xlsxCells($this->actingAs($this->counselorA)->get(route('staff.records.export', [$this->recordA, 'format' => 'xlsx'])));
        $this->assertNotContains('ENTRANCE TEST RESULT (SATA)', $without);
        $this->assertNotContains('Secret intake note', $without);

        $with = $this->xlsxCells($this->actingAs($this->counselorA)->get(route('staff.records.export', [$this->recordA, 'format' => 'xlsx', 'include' => ['sata', 'intake']])));
        $this->assertContains('ENTRANCE TEST RESULT (SATA)', $with);
        $this->assertContains('111', $with);
        $this->assertContains('Secret intake note', $with);
    }

    public function test_counselor_cannot_export_outside_assigned_colleges(): void
    {
        foreach ([[], ['sata'], ['intake']] as $include) {
            $this->actingAs($this->counselorB)
                ->get(route('staff.records.export', [$this->recordA, 'format' => 'pdf', 'include' => $include]))
                ->assertForbidden();
        }

        $this->assertSame(0, AccessLog::where('action', AccessLog::ACTION_EXPORT_RECORD)->count());
    }

    public function test_students_can_only_download_their_own_form_5_as_pdf(): void
    {
        $response = $this->actingAs($this->studentA)->get(route('student.record.pdf', [$this->recordA, 'include' => ['sata', 'intake']]))->assertOk();
        $this->assertStringStartsWith('%PDF', $this->downloaded($response));
        $this->assertSame('format: pdf; sections: form5', AccessLog::where('action', AccessLog::ACTION_EXPORT_RECORD)->sole()->details);

        // Not someone else's record, and never the staff export (other formats, SATA, Form 8).
        $other = User::factory()->student($this->studentA->program)->create();
        $this->actingAs($other)->get(route('student.record.pdf', $this->recordA))->assertForbidden();
        $this->actingAs($this->studentA)->get(route('staff.records.export', [$this->recordA, 'format' => 'xlsx']))->assertForbidden();
        $this->actingAs($this->studentA)->get(route('staff.records.export', [$this->recordA, 'format' => 'pdf', 'include' => ['intake']]))->assertForbidden();

        $this->actingAs($this->studentA)->get(route('student.record.show', $this->recordA))
            ->assertSee(route('student.record.pdf', $this->recordA))
            ->assertDontSee('include[]', false);
    }

    public function test_form_8_option_is_offered_only_to_authorized_staff_and_inclusion_is_enforced(): void
    {
        $this->actingAs($this->counselorA)->get(route('staff.records.show', $this->recordA))
            ->assertSee('value="intake"', false)
            ->assertSee('value="sata"', false);

        // Forged request for Form 8 by a user who may not see it.
        $this->actingAs($this->counselorB)->get(route('staff.records.export', [$this->recordA, 'format' => 'xlsx', 'include' => ['intake']]))->assertForbidden();
        $this->actingAs($this->counselorA)->get(route('staff.records.export', [$this->recordA, 'format' => 'xlsx', 'include' => ['bogus']]))->assertSessionHasErrors('include.0');
    }

    public function test_record_exports_are_logged_with_format_and_sections(): void
    {
        $this->downloaded($this->actingAs($this->director)->get(route('staff.records.export', [$this->recordA, 'format' => 'docx', 'include' => ['sata', 'intake']])));

        $log = AccessLog::where('action', AccessLog::ACTION_EXPORT_RECORD)->sole();
        $this->assertSame($this->director->id, $log->user_id);
        $this->assertSame($this->recordA->id, $log->cumulative_record_id);
        $this->assertStringStartsWith('format: docx; sections: form5, sata, intake; intake ids: ', $log->details);
    }

    // ---- Lists ---------------------------------------------------------------------------------

    public function test_list_export_respects_filters_and_college_scoping(): void
    {
        User::factory()->student($this->studentA->program)->create(['last_name' => 'Bautista', 'year_level' => 2]);
        User::factory()->student(Program::factory()->for(College::where('code', 'CON')->first())->create())->create(['last_name' => 'Castro', 'year_level' => 1]);

        $all = $this->xlsxCells($this->actingAs($this->counselorA)->get(route('staff.records.export-list', ['format' => 'xlsx'])));
        $this->assertContains('Aquino', $all);
        $this->assertContains('Bautista', $all);
        $this->assertNotContains('Castro', $all, 'Students outside the counselor\'s colleges are never exported.');
        foreach (['Student no.', 'Program', 'College', 'Year level', 'Form 5 status', 'Submitted', 'SATA encoded', 'Intake status'] as $header) {
            $this->assertContains($header, $all);
        }
        $this->assertNotContains('Mobile no.', $all);
        $this->assertNotContains('09170000001', $all);

        $filtered = $this->xlsxCells($this->actingAs($this->counselorA)->get(route('staff.records.export-list', ['format' => 'xlsx', 'year_level' => 2])));
        $this->assertContains('Bautista', $filtered);
        $this->assertNotContains('Aquino', $filtered);

        $csv = $this->downloaded($this->actingAs($this->director)->get(route('staff.records.export-list', ['format' => 'csv', 'q' => 'Castro'])));
        $this->assertStringContainsString('Castro', $csv);
        $this->assertStringNotContainsString('Aquino', $csv);
        $this->assertStringContainsString('Search: Castro', $csv);

        $pdf = $this->actingAs($this->counselorA)->get(route('staff.records.export-list', ['format' => 'pdf']))->assertOk();
        $this->assertStringStartsWith('%PDF', $this->downloaded($pdf));
    }

    public function test_only_the_director_can_export_sensitive_fields(): void
    {
        $this->actingAs($this->counselorA)->get(route('staff.records.export-list', ['format' => 'xlsx', 'sensitive' => 1]))->assertForbidden();
        $this->actingAs($this->counselorA)->get(route('staff.records.index'))->assertDontSee('name="sensitive"', false);

        $cells = $this->xlsxCells($this->actingAs($this->director)->get(route('staff.records.export-list', ['format' => 'xlsx', 'sensitive' => 1])));
        $this->assertContains('Mobile no.', $cells);
        $this->assertContains('09170000001', $cells);
        $this->assertContains('111', $cells);
        $this->assertNotContains('Secret intake note', $cells, 'Form 8 answers never go into a list.');

        $page = $this->actingAs($this->director)->get(route('staff.records.index'))->getContent();
        $this->assertStringContainsString('name="sensitive"', $page);
        $this->assertStringContainsString('x-bind:data-confirm="sensitive ? $el.dataset.sensitiveMessage : null"', $page);
    }

    public function test_list_exports_are_logged(): void
    {
        $this->downloaded($this->actingAs($this->counselorA)->get(route('staff.records.export-list', ['format' => 'csv', 'year_level' => 1])));

        $log = AccessLog::where('action', AccessLog::ACTION_EXPORT_LIST)->sole();
        $this->assertSame($this->counselorA->id, $log->user_id);
        $this->assertStringContainsString('format: csv; students: 1; sensitive: no; Year level: 1st Year', $log->details);
    }

    public function test_csv_cells_cannot_become_formulas(): void
    {
        $this->studentA->update(['last_name' => '=HYPERLINK("http://evil")']);

        $csv = $this->downloaded($this->actingAs($this->director)->get(route('staff.records.export-list', ['format' => 'csv'])));
        $this->assertStringContainsString("'=HYPERLINK", $csv);
    }

    public function test_a_failed_export_shows_a_friendly_message(): void
    {
        $this->app->bind('dompdf.wrapper', fn () => throw new \RuntimeException('renderer down'));

        $this->actingAs($this->counselorA)->from(route('staff.records.show', $this->recordA))
            ->get(route('staff.records.export', [$this->recordA, 'format' => 'pdf']))
            ->assertRedirect(route('staff.records.show', $this->recordA))
            ->assertSessionHas('error');
        $this->assertSame(0, AccessLog::where('action', AccessLog::ACTION_EXPORT_RECORD)->count());
    }
}
